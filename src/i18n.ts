export function resolveUiLanguage(appLanguage?: string | null, browserLanguage?: string | null): UiLanguage {
	const language = appLanguage?.trim() || browserLanguage?.trim() || "zh";
	return /^zh(?:[-_]|$)/i.test(language) ? "zh" : "en";
}

export function getUiLanguage(): UiLanguage {
	let language: string | undefined;
	try {
		// getLanguage is public since Obsidian 1.8.7; older supported hosts fall back below.
		if (typeof obsidian.getLanguage === "function") language = obsidian.getLanguage();
	} catch { /* Browser storage can be unavailable in a sandboxed window. */ }
	return resolveUiLanguage(language, typeof navigator !== "undefined" ? navigator.language : undefined);
}

export function translate(key: string, language: UiLanguage, params: TranslationParams = {}): string {
	const text = language === "en" ? ENGLISH[key] ?? key : key;
	return text.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (placeholder, name: string) =>
		Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : placeholder);
}

export function t(key: string, params: TranslationParams = {}): string {
	return translate(key, getUiLanguage(), params);
}
